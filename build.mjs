// Builds the browser apps from TypeScript. Run with `npm run build` (or
// `npm run watch`). Type-checking is separate: `npm run check`.
//
// Each app's src/ is bundled into one plain script (not a module), so pages
// also work when opened straight from disk, and GitHub Pages can serve the
// committed output without a build step.
import * as esbuild from 'esbuild';

const banner = {
  js: '// Generated from TypeScript in src/ by `npm run build`. Do not edit this file directly.',
};
const common = {
  bundle: true,
  format: 'iife',
  target: ['es2020', 'safari14'],
  charset: 'utf8',
  logLevel: 'info',
  banner,
};

const builds = [
  // LocalChatter: the app bundle and its service worker (which must sit at the app root).
  { entryPoints: ['PWA/LocalChatter/src/main.ts'], outfile: 'PWA/LocalChatter/dist/app.js' },
  { entryPoints: ['PWA/LocalChatter/src/sw.ts'], outfile: 'PWA/LocalChatter/sw.js' },
  // Hello World sample.
  { entryPoints: ['PWA/Sample/src/app.ts'], outfile: 'PWA/Sample/app.js' },
  { entryPoints: ['PWA/Sample/src/sw.ts'], outfile: 'PWA/Sample/sw.js' },
];

const watch = process.argv.includes('--watch');
for (const b of builds) {
  const options = { ...common, ...b };
  if (watch) await (await esbuild.context(options)).watch();
  else await esbuild.build(options);
}
if (watch) console.log('Watching for changes…');
